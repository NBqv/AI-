def main():
    print(f"将重新生成 {len(BAD_NAMES)} 个模板，使用 qwen-max")
    print()

    # 先删除旧的坏模板
    import json
    from pathlib import Path
    aliases_path = Path(__file__).parent / "aliases.json"
    with open(aliases_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    removed = 0
    for name in BAD_NAMES:
        if name in data.get("complex_shapes", {}):
            del data["complex_shapes"][name]
            removed += 1
    with open(aliases_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"已删除 {removed} 个旧模板")

    # 分批，每批5个
    items_with_hints = [(name, CATEGORY_HINTS.get(name, f"{name}的简笔画")) for name in BAD_NAMES]

    total_added = 0

    for i in range(0, len(items_with_hints), 5):
        chunk = items_with_hints[i:i+5]
        names = [c[0] for c in chunk]
        print(f"\n--- [{i+1}-{i+len(chunk)}/{len(BAD_NAMES)}] {' '.join(names)} ---")
        content = call_qwen(chunk, "regenerate")
        if content:
            templates = parse_result(content)
            if templates:
                added = merge_into_aliases(templates)
                if added:
                    total_added += added
        time.sleep(2)

    print(f"\n完成！共重生成 {total_added} 个模板")


if __name__ == "__main__":
    main()
